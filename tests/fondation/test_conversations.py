def test_lit_seulement_les_256_premiers_kio(projet, monkeypatch):
    remplissage = [assistant("x" * 1000) for _ in range(4000)]          # ≈ 4 Mo avant
    f = ecrire(projet, "gros", [*remplissage, utilisateur(HUMAIN)])
    assert f.stat().st_size > 3 * 1024 * 1024
    lus = []
    vrai_ouvrir = conversations._ouvrir

    class Compteur:
        def __init__(self, fichier):
            self.f = vrai_ouvrir(fichier)

        def __getattr__(self, nom):
            attr = getattr(self.f, nom)
            if nom not in ("read", "readline", "readlines", "read1", "readinto"):
                return attr

            def mesure(*a, **k):
                r = attr(*a, **k)
                lus.append(len(r) if hasattr(r, "__len__") else 0)
                return r
            return mesure

        def __iter__(self):
            for ligne in self.f:
                lus.append(len(ligne))
                yield ligne

        def __enter__(self):
            return self

        def __exit__(self, *a):
            self.f.close()

    monkeypatch.setattr(conversations, "_ouvrir", Compteur)
    (r,) = conversations.lister(projet)
    assert r["debut"] is None                              # le message humain est après 256 Kio
    assert r["taille"] == f.stat().st_size               # mais la taille est celle du fichier
    assert 0 < sum(lus) <= MAX_LECTURE


