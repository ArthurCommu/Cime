# --- la commande ------------------------------------------------------------------------------

def lancer_cli(capsys, *argv):
    code = cli.main(list(argv))
    sortie = capsys.readouterr()
    return code, sortie.out, sortie.err


def test_json(projet, capsys):
    ecrire(projet, "s1", [utilisateur(lancer.MESSAGE_ASSISTANT), utilisateur(HUMAIN)], mtime=2000)
    ecrire(projet, "s0", [utilisateur("avant")], mtime=1000)
    code, sortie, _ = lancer_cli(capsys, "conversations", str(projet), "--json")
    assert code == 0
    donnees = json.loads(sortie)
    assert list(donnees) == ["conversations"]
    assert [c["session"] for c in donnees["conversations"]] == ["s1", "s0"]
    assert donnees["conversations"][0]["debut"] == HUMAIN


def test_json_sans_conversation_code_0(projet, capsys):
    code, sortie, _ = lancer_cli(capsys, "conversations", str(projet), "--json")
    assert code == 0 and json.loads(sortie) == {"conversations": []}


def test_texte_une_ligne_par_conversation(projet, capsys):
    ecrire(projet, "s1", [utilisateur(HUMAIN)], mtime=2000)
    ecrire(projet, "s0", [utilisateur("avant")], mtime=1000)
