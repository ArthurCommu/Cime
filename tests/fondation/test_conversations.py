def test_lecture_seule(projet, capsys):
    ecrire(projet, "s", [utilisateur(HUMAIN)])
    avant = {p: p.read_bytes() for p in projet.parent.rglob("*") if p.is_file()}
    avant_dossiers = {p for p in projet.parent.rglob("*")}
    lancer_cli(capsys, "conversations", str(projet), "--json")
    assert {p: p.read_bytes() for p in projet.parent.rglob("*") if p.is_file()} == avant
    assert {p for p in projet.parent.rglob("*")} == avant_dossiers


