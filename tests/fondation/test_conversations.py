MAX_LECTURE = 256 * 1024


@pytest.fixture(autouse=True)
def monde(tmp_path, monkeypatch):
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    for var in (VAR_AGENT, "CLAUDECODE"):
        monkeypatch.delenv(var, raising=False)


@pytest.fixture
def projet(tmp_path):
    p = tmp_path / "projet"
    (p / ".orga").mkdir(parents=True)
    (p / ".orga" / "projet.toml").write_text('nom = "projet"\n')
    return p


# --- fabrication de transcripts ---------------------------------------------------------------

def utilisateur(contenu, **plus):
    return {"parentUuid": None, "isSidechain": False, "userType": "external",
            "type": "user", "message": {"role": "user", "content": contenu},
            "uuid": "u-1", "timestamp": "2026-10-12T10:00:00.000Z", **plus}


def assistant(texte):
    return {"type": "assistant", "uuid": "a-1",
            "message": {"role": "assistant", "content": [{"type": "text", "text": texte}]}}


def resultat_outil(texte):
    return utilisateur([{"tool_use_id": "toolu_01", "type": "tool_result", "content": texte}],
                       toolUseResult={"stdout": texte})


def ecrire(projet, session, lignes, mtime=None, brut=False):
    sous = lancer.dossier_conversations(projet)
    sous.mkdir(parents=True, exist_ok=True)
    f = sous / f"{session}.jsonl"
    if brut:
        f.write_bytes(lignes)
    else:
        f.write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in lignes))
    if mtime is not None:
        os.utime(f, (mtime, mtime))
    return f


def debut_de(projet, lignes):
    ecrire(projet, "s", lignes)
    (r,) = conversations.lister(projet)
    return r["debut"]


