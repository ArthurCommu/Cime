"""`cime conversations <projet> [--json]` : les conversations de l'Assistant, avec leur début
(le premier message humain, pas ce que Cime et Claude Code écrivent eux-mêmes).

Les fixtures sont fabriquées à la main, d'après la forme des transcripts de Claude Code
(une ligne JSON par événement : `type` user/assistant/system/attachment…, `message.content`
chaîne ou liste de blocs `text` / `tool_result`, drapeaux `isMeta` / `isCompactSummary`)."""
