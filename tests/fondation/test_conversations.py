def test_fichier_enorme_reste_rapide(projet):
    f = ecrire(projet, "enorme", [utilisateur(HUMAIN)])
    with open(f, "ab") as o:
        o.truncate(300 * 1024 * 1024)                                    # fichier creux
    debut = time.monotonic()
    (r,) = conversations.lister(projet)
    assert time.monotonic() - debut < 1.0
    assert r["debut"] == HUMAIN and r["taille"] == 300 * 1024 * 1024


