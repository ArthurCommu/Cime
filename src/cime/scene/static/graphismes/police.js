// Chaque glyphe : 7 chaînes de 5 caractères, « # » = encre (colorée par le
// moteur), « . » = vide.
// Métrique : capitales et chiffres sur les lignes 0 à 5, ligne de base = 5,
// minuscules de la ligne 2 à 5, jambages en ligne 6. Les accents des
// minuscules occupent les lignes 0-1. Les capitales accentuées sont réduites :
// 5 lignes sous un aigu/grave d'une ligne, 4 lignes sous un circonflexe/tréma.

const VIDE = ".....";

// Glyphe dont les lignes commencent à la ligne `debut`.
function G(debut, ...lignes) {
  const r = Array(7).fill(VIDE);
  lignes.forEach((l, i) => (r[debut + i] = l));
  return r;
}

