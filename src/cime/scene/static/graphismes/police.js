// Accents
const ACCENTS_MIN = {
  aigu: ["...#.", "..#.."],
  grave: [".#...", "..#.."],
  circonflexe: ["..#..", ".#.#."],
  trema: [".#.#.", VIDE],
};
const ACCENTS_CAP = {
  aigu: "...#.",
  grave: ".#...",
};

const SANS_POINT = G(2, ".##..", "..#..", "..#..", ".###."); // ı

function accentMin(base, accent) {
  const g = [...(base === "i" ? SANS_POINT : MINUSCULES[base])];
  g[0] = ACCENTS_MIN[accent][0];
  g[1] = ACCENTS_MIN[accent][1];
  return g;
}

function accentCap(base, accent) {
  if (accent in ACCENTS_CAP) return [ACCENTS_CAP[accent], ...CAPITALES_COURTES[base], VIDE];
  return [...ACCENTS_MIN[accent], ...CAPITALES_BASSES[base], VIDE];
}

const ACCENTUEES = {};
const TABLE = {
  aigu: { é: "e", É: "E" },
  grave: { è: "e", à: "a", ù: "u", È: "E", À: "A", Ù: "U" },
  circonflexe: { ê: "e", â: "a", î: "i", ô: "o", û: "u", Ê: "E", Â: "A", Î: "I", Ô: "O", Û: "U" },
  trema: { ë: "e", ï: "i", ü: "u", ä: "a", ö: "o", ÿ: "y", Ë: "E", Ï: "I", Ü: "U", Ä: "A", Ö: "O", Ÿ: "Y" },
};
for (const [accent, lettres] of Object.entries(TABLE)) {
  for (const [lettre, base] of Object.entries(lettres)) {
    ACCENTUEES[lettre] = base === base.toLowerCase() ? accentMin(base, accent) : accentCap(base, accent);
  }
}
